    if all_product_preempt:
        readable_logic = readable_logic.replace("_PREEMPT_MAX_BATCH = 30", "_PREEMPT_MAX_BATCH = 100")
        readable_logic = readable_logic.replace("_PREEMPT_STOP = 680", "_PREEMPT_STOP = 719")
