"""Build a transparent Kaggriculture submission from a tested route module.

The output intentionally stores strategy tables as normal Python literals.
There is no compression, encoding, dynamic evaluation, or generated bytecode in
the submission.  Keeping this builder separate makes route experiments
repeatable while leaving ``main.py`` directly inspectable by humans.
"""

