def _legal_unit_actions(obs, actor_index):
    """Generate every contextually legal command for one worker.

    Movement is always accepted by the simulator (an edge move is a no-op), so
    all four directions remain in the legal frontier.  Resource actions are
    emitted only when the public/private state shows they can have an effect.
    """
    _seat, farm = _farm(obs)
    private = _get(obs, "private", {}) or {}
    positions = [_get(farm, "farmer", [0, 0]), *list(_get(farm, "hands", []) or [])]
    inventories = list(_get(private, "inventories", []) or [])
    if actor_index >= len(positions):
        return [["PASS"]]
    position = positions[actor_index]
    inventory = dict(inventories[actor_index] or {}) if actor_index < len(inventories) else {}
    seeds = dict(_get(private, "seeds", {}) or {})
    shed = dict(_get(private, "shed", {}) or {})
    tile = _tile_at(farm, position)
    actions = [["PASS"], *[[direction] for direction in _DIRECTIONS]]

    if tile is None:
        actions.extend([["BUILD_COOP"], ["BUILD_PASTURE"]])
        actions.extend([["PLANT", crop] for crop in _CROPS if int(seeds.get(crop, 0) or 0) > 0])
    elif isinstance(tile, dict):
        kind = str(tile.get("kind", "")).upper()
        animal = str(tile.get("animal", "")).upper()
        if kind == "WEED":
            actions.append(["DIG"])
        elif kind == "PLANT":
            actions.append(["DIG"])
            if not tile.get("watered_today", False):
                actions.append(["WATER"])
            if int(inventory.get("FERTILIZER", 0) or 0) > 0:
                actions.append(["FERTILIZE"])
            if int(tile.get("yield_units", 0) or 0) > 0:
                actions.append(["HARVEST"])
        elif kind in ("COOP", "PASTURE"):
            if animal:
                if not tile.get("cared_today", False):
                    actions.append(["CARE"])
                if not tile.get("fed_today", False) and int(inventory.get("WHEAT", 0) or 0) > 0:
                    actions.append(["FEED"])
                if int(tile.get("yield_units", 0) or 0) > 0:
                    actions.append(["HARVEST"])
                if tile.get("fertilizer_available", False):
                    actions.append(["COLLECT_FERTILIZER"])
            else:
                actions.append(["DIG"])
                compatible = ("GOOSE",) if kind == "COOP" else ("COW", "SHEEP")
                actions.extend([["PLACE", item, 1] for item in compatible
                                if int(inventory.get(item, 0) or 0) > 0])

    tiles = list(_get(farm, "tiles", []) or [])
    try:
        adjacent = (int(position[0]), int(position[1])) in _shed_access(len(tiles) or 10)
    except (TypeError, ValueError, IndexError):
        adjacent = False
    if adjacent:
        if any(int(value or 0) > 0 for value in inventory.values()):
            actions.append(["DROP"])
        actions.extend([["PICKUP", item, int(quantity)] for item, quantity in shed.items()
                        if int(quantity or 0) > 0])
        actions.extend([["PLACE", item, int(quantity)] for item, quantity in inventory.items()
                        if int(quantity or 0) > 0])
    return actions


def _legal_market_orders(obs):
    """Generate the complete one-order market frontier for search/recovery."""
    _seat, farm = _farm(obs)
    private = _get(obs, "private", {}) or {}
    shed = dict(_get(private, "shed", {}) or {})
    orders = []
    orders.extend([["BUY_SEED", crop, 1] for crop in _CROPS])
    orders.extend([["BUY_ANIMAL", animal, 1] for animal in _ANIMALS])
    orders.extend([["BUY_PRODUCT", item, 1] for item in ("WHEAT", "FERTILIZER")])
    orders.extend([["SELL", item, int(shed.get(item, 0) or 0)] for item in _PRODUCTS
                   if int(shed.get(item, 0) or 0) > 0])
    orders.append(["HIRE"])
    if len(_get(farm, "unlocked_quadrants", []) or []) < 4:
        orders.append(["BUY_LAND"])
    return orders


def _recovery_agent(obs):
    """Choose survival-first moves if the principal evaluator ever raises."""
    _seat, farm = _farm(obs)
    unit_count = 1 + len(_get(farm, "hands", []) or [])
    priorities = {
        "FEED": 100, "WATER": 95, "HARVEST": 85,
        "COLLECT_FERTILIZER": 75, "CARE": 65, "DIG": 45,
        "DROP": 35, "PASS": 0,
    }
    chosen = []
    for actor_index in range(unit_count):
        legal = _legal_unit_actions(obs, actor_index)
        chosen.append(max(legal, key=lambda row: priorities.get(row[0], 5)))
    action = {"farmer": chosen[0], "hands": chosen[1:], "market": []}
    if _step(obs) == len(_ACTIONS) - 1:
        action = _terminal_market(obs, action)
    return action


def agent(obs):
    try:
        step = _step(obs)
        action = _weed_repair_action(obs, _copy_action(_ACTIONS[step]), step)
        action = _repay_shift(obs, action, step)
        action = _safe_market(obs, action)
        action = _preempt_shift(obs, action, step)
        action = _safe_market(obs, action)
        if step == len(_ACTIONS) - 1:
            action = _terminal_market(obs, action)
        return _align_hands(action, obs)
    except Exception:
        try:
            return _recovery_agent(obs)
        except Exception:
            _seat, farm = _farm(obs)
            return {
                "farmer": ["PASS"],
                "hands": [["PASS"] for _ in (_get(farm, "hands", []) or [])],
                "market": [],
            }


def _kaggle_submission_entrypoint(obs):
    return agent(obs)
